"""Physical-bearing readiness audit and nested OOF split plan, without ML extras."""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import numpy as np

from ai.signal_pipeline.paderborn import file_sha256
from .hybrid import ModelInputError
from .paderborn_experiment import select_samples


def audit_groups(rows):
    groups = {}
    seen = set()
    for row in rows:
        group, label = row["split_group"], row["fault_label"]
        if not row["sample_id"] or row["sample_id"] in seen:
            raise ModelInputError("empty or duplicate sample identity")
        seen.add(row["sample_id"])
        if group != f"paderborn-bearing-{row['bearing_code'].lower()}":
            raise ModelInputError("split group must identify physical bearing")
        if group in groups and groups[group] != label:
            raise ModelInputError("conflicting bearing labels")
        groups[group] = label
    classes = sorted(set(groups.values()))
    if len(classes) < 2:
        raise ModelInputError("at least two classes required")
    counts = {label: sum(value == label for value in groups.values()) for label in classes}
    deficits = {label: max(0, 3 - count) for label, count in counts.items()}
    return {"status": "READY_FOR_EXPLORATORY_NESTED_OOF" if not any(deficits.values()) else "BLOCKED_INSUFFICIENT_BEARINGS",
            "bearings_per_class": counts, "additional_bearings_minimum": deficits,
            "minimum_basis": "one outer held-out bearing plus at least two inner train/OOF bearings per class",
            "warning": "Three bearings/class is only a structural minimum, not sufficient statistical validation or independent calibration."}


def nested_bearing_plan(rows, seed=7):
    """Generate sample-index plans; outer test never appears in inner gate data.

    Gate inputs must later be generated by fitting branches separately in each
    inner split. A split plan alone does not train or validate a learned gate.
    """
    audit = audit_groups(rows)
    if audit["status"] != "READY_FOR_EXPLORATORY_NESTED_OOF":
        raise ModelInputError("nested OOF requires at least three physical bearings per class")
    rng = np.random.default_rng(seed)
    groups = {}
    for label in audit["bearings_per_class"]:
        values = sorted({r["split_group"] for r in rows if r["fault_label"] == label})
        rng.shuffle(values)
        groups[label] = values
    # Use the smallest class group count so every outer fold has all classes.
    fold_count = min(map(len, groups.values()))
    result = []
    for outer in range(fold_count):
        test_groups = {g for values in groups.values() for j, g in enumerate(values) if j % fold_count == outer}
        test = [i for i, r in enumerate(rows) if r["split_group"] in test_groups]
        train = [i for i, r in enumerate(rows) if r["split_group"] not in test_groups]
        remaining = {label: [g for g in values if g not in test_groups] for label, values in groups.items()}
        inner_count = min(map(len, remaining.values()))
        inner = []
        for fold in range(inner_count):
            valid_groups = {g for values in remaining.values() for j, g in enumerate(values) if j % inner_count == fold}
            inner.append({"train": [i for i in train if rows[i]["split_group"] not in valid_groups],
                          "validation": [i for i in train if rows[i]["split_group"] in valid_groups]})
        result.append({"train": train, "test": test, "inner": inner})
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, default=Path("docs/data/signal-sample-manifest.csv"))
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    with args.manifest.open(encoding="utf-8-sig", newline="") as stream:
        rows, excluded = select_samples(list(csv.DictReader(stream)))
    report = {"schema_version": "bearing-validation-readiness.v0.2", "manifest_sha256": file_sha256(args.manifest),
              "included_samples": len(rows), "excluded_samples": len(excluded), **audit_groups(rows),
              "gate_training_enabled": False,
              "next_action": "Register more independently labelled physical bearings; more runs/windows from existing bearings do not satisfy deficits."}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report))


if __name__ == "__main__":
    main()
